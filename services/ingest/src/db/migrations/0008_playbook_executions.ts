import { type Kysely, sql } from "kysely";

/**
 * SPEC-022 §Data contracts §2 / ADR-0021 §4 — one execution record per playbook
 * and incident: claimed `running` before the first step (the unique key is the
 * idempotency key), completed once, then refused any change. The write-once rule
 * lives in Postgres, in `playbook_executions_write_once`:
 *
 * - INSERT: only a `running` row, with empty `steps` and null `finished_at` /
 *   `chain_head` (a claim);
 * - UPDATE: only from `running`, to a status that is not `running`, touching only
 *   `status`, `finished_at`, `steps` and `chain_head`;
 * - DELETE and TRUNCATE: never.
 *
 * It holds against a writer that goes through the application, not against the
 * database's owner, who can drop the trigger (ADR-0021 §4).
 */
export async function up(db: Kysely<unknown>): Promise<void> {
  await sql`
    CREATE TABLE IF NOT EXISTS playbook_executions (
      execution_id      uuid        PRIMARY KEY,                 -- UUIDv7, generated by ingest
      org_id            text        NOT NULL,
      incident_id       uuid        NOT NULL REFERENCES incidents (incident_id),
      agent_id          uuid        NOT NULL,
      playbook_id       text        NOT NULL,
      playbook_version  integer     NOT NULL,
      status            text        NOT NULL DEFAULT 'running'
                          CHECK (status IN ('running', 'completed', 'failed')),
      started_at        timestamptz NOT NULL DEFAULT now(),
      finished_at       timestamptz,
      steps             jsonb       NOT NULL DEFAULT '[]'::jsonb,
      chain_head        text        CHECK (chain_head ~ '^[0-9a-f]{64}$'),
      CONSTRAINT playbook_executions_once UNIQUE (org_id, playbook_id, incident_id)
    )
  `.execute(db);
  await sql`
    CREATE INDEX IF NOT EXISTS playbook_executions_incident
      ON playbook_executions (org_id, incident_id, started_at, execution_id)
  `.execute(db);
  await sql`
    CREATE OR REPLACE FUNCTION playbook_executions_write_once() RETURNS trigger
    LANGUAGE plpgsql AS $$
    BEGIN
      IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'running' OR NEW.steps <> '[]'::jsonb
           OR NEW.finished_at IS NOT NULL OR NEW.chain_head IS NOT NULL THEN
          RAISE EXCEPTION 'playbook_executions: a new row must be a running claim';
        END IF;
        RETURN NEW;
      ELSIF TG_OP = 'UPDATE' THEN
        IF OLD.status <> 'running' THEN
          RAISE EXCEPTION 'playbook_executions: a completed row is never changed';
        END IF;
        IF NEW.status = 'running' THEN
          RAISE EXCEPTION 'playbook_executions: an update must complete the row';
        END IF;
        IF NEW.execution_id IS DISTINCT FROM OLD.execution_id
           OR NEW.org_id IS DISTINCT FROM OLD.org_id
           OR NEW.incident_id IS DISTINCT FROM OLD.incident_id
           OR NEW.agent_id IS DISTINCT FROM OLD.agent_id
           OR NEW.playbook_id IS DISTINCT FROM OLD.playbook_id
           OR NEW.playbook_version IS DISTINCT FROM OLD.playbook_version
           OR NEW.started_at IS DISTINCT FROM OLD.started_at THEN
          RAISE EXCEPTION 'playbook_executions: only status, finished_at, steps and chain_head change';
        END IF;
        RETURN NEW;
      ELSE
        RAISE EXCEPTION 'playbook_executions: rows are never deleted or truncated';
      END IF;
    END
    $$
  `.execute(db);
  await sql`DROP TRIGGER IF EXISTS playbook_executions_write_once_row ON playbook_executions`.execute(
    db,
  );
  await sql`
    CREATE TRIGGER playbook_executions_write_once_row
      BEFORE INSERT OR UPDATE OR DELETE ON playbook_executions
      FOR EACH ROW EXECUTE FUNCTION playbook_executions_write_once()
  `.execute(db);
  await sql`DROP TRIGGER IF EXISTS playbook_executions_no_truncate ON playbook_executions`.execute(
    db,
  );
  await sql`
    CREATE TRIGGER playbook_executions_no_truncate
      BEFORE TRUNCATE ON playbook_executions
      FOR EACH STATEMENT EXECUTE FUNCTION playbook_executions_write_once()
  `.execute(db);
}

